"""One recorder for every area of the independent numerical review.

Each area script computes its reference values from first principles and calls
the module under review only to compare. A check records the reference, the
module's value, the tolerance and the verdict. A failed check is recorded and
reported, never raised away or retried with a wider tolerance.
"""
from datetime import datetime, timezone
import json
import math
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))  # review this worktree's code, not an installed copy


class Review:
    def __init__(self, area, title, script):
        self.area, self.title = area, title
        self.folder = Path(script).resolve().parent
        self.checks = []

    def close(self, check_id, what, source, reference, value, abs_tol=0.0, rel_tol=0.0, compared="module"):
        """Numeric check by math.isclose: |value - reference| <= max(rel_tol * max(|value|, |reference|), abs_tol)."""
        reference, value = float(reference), float(value)
        passed = math.isfinite(value) and math.isclose(value, reference, abs_tol=abs_tol, rel_tol=rel_tol)
        self.checks.append(dict(id=check_id, what=what, source=source, compared=compared,
                                reference=reference, value=value, difference=value - reference,
                                abs_tol=abs_tol, rel_tol=rel_tol, passed=passed))

    def equal(self, check_id, what, source, reference, value, compared="module"):
        self.checks.append(dict(id=check_id, what=what, source=source, compared=compared,
                                reference=reference, value=value, difference=None,
                                abs_tol=None, rel_tol=None, passed=reference == value))

    def write(self):
        failed = [c["id"] for c in self.checks if not c["passed"]]
        payload = dict(area=self.area, title=self.title,
                       generated_utc=datetime.now(timezone.utc).isoformat(),
                       checks=self.checks, passed=len(self.checks) - len(failed), failed=failed)
        (self.folder / "numerical-results.json").write_text(
            json.dumps(payload, indent=2, allow_nan=False) + "\n", encoding="utf-8")
        lines = [f"# {self.title}", "",
                 "Generated by `checks.py` in this folder; do not edit by hand. "
                 "Reference values are computed in that script from first principles or taken from the "
                 "cited publication; the module is called only for comparison.", "",
                 f"Checks: {len(self.checks)}. Passed: {len(self.checks) - len(failed)}. "
                 f"Failed: {len(failed)}" + (f" ({', '.join(failed)})." if failed else "."), "",
                 "| Check | Result | Compared | Reference | Value | Tolerance | Source |",
                 "|---|---|---|---|---|---|---|"]
        for c in self.checks:
            tol = ("exact" if c["abs_tol"] is None or (c["abs_tol"] == 0 and c["rel_tol"] == 0) else
                   " or ".join(t for t in (f"abs {c['abs_tol']:g}" if c["abs_tol"] else "",
                                           f"rel {c['rel_tol']:g}" if c["rel_tol"] else "") if t))
            lines.append(f"| {c['id']}: {c['what']} | {'PASS' if c['passed'] else 'FAIL'} | {c['compared']} | "
                         f"{_show(c['reference'])} | {_show(c['value'])} | {tol} | {c['source']} |")
        (self.folder / "report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
        return payload


def _show(x):
    return f"{x:.10g}" if isinstance(x, float) else str(x)
